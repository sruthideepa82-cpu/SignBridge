"""Writes the frontend's view of the candidate vocabulary, so the UI and the recording tools use the same data.

Usage (from the ai-engine folder):  python collection/export_vocabulary_for_frontend.py
The frontend test suite fails if the generated file no longer matches vocabulary.json.
"""

import json
from pathlib import Path

AI_ENGINE_DIR = Path(__file__).resolve().parents[1]
VOCABULARY = AI_ENGINE_DIR / "dataset" / "metadata" / "vocabulary.json"
OUTPUT = AI_ENGINE_DIR.parent / "frontend" / "src" / "data" / "fingerspelling.js"

FIELDS = (
    "label",
    "class_id",
    "recognition_type",
    "verification_status",
    "training_status",
    "source",
    "verified",
    "meaning",
    "reference",
    "signer_confirmed",
)


def main() -> None:
    data = json.loads(VOCABULARY.read_text(encoding="utf-8"))
    classes = [{field: entry.get(field) for field in FIELDS} for entry in data["classes"]]
    verified = sum(1 for entry in classes if entry["verified"] is True)
    body = json.dumps(classes, ensure_ascii=False, indent=2)
    lines = [
        "// Generated by ai-engine/collection/export_vocabulary_for_frontend.py from dataset/metadata/vocabulary.json.",
        "// Do not edit by hand.",
        "",
        f"export const FINGERSPELLING_CLASSES = {body};",
        "",
        f"export const CONSENT_STATUS = {json.dumps(data['consent']['status'])};",
        f"export const VERIFIED_CLASS_COUNT = {verified};",
        "",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT}: {len(classes)} classes, {verified} verified")


if __name__ == "__main__":
    main()
