"""Writes the frontend's view of the daily phrase catalog.

Usage (from the ai-engine folder):  python collection/export_phrase_vocabulary_for_frontend.py
The frontend test suite fails if the generated file no longer matches phrase_vocabulary.json.

Status fields are kept apart, as in export_vocabulary_for_frontend.py. recognition_status is what the phrase
model covers. It is not an approval, so a phrase is training_ready only when it is verified and in the model.
"""

import json
from pathlib import Path

AI_ENGINE_DIR = Path(__file__).resolve().parents[1]
VOCABULARY = AI_ENGINE_DIR / "dataset" / "metadata" / "phrase_vocabulary.json"
OUTPUT = AI_ENGINE_DIR.parent / "frontend" / "src" / "data" / "phraseVocabulary.js"
ANIMATIONS = AI_ENGINE_DIR.parent / "frontend" / "public" / "animations"

FIELDS = (
    "id",
    "label",
    "display_name",
    "category",
    "reference_folder",
    "reference_image_count",
    "recognition_status",
    "recognition_model_label",
    "asset_name",
    "verified",
    "signer_confirmed",
)


def main() -> None:
    data = json.loads(VOCABULARY.read_text(encoding="utf-8"))
    phrases = []
    for phrase in data["phrases"]:
        item = {field: phrase.get(field) for field in FIELDS}
        item["asset_available"] = (ANIMATIONS / "phrases" / f"{phrase['asset_name']}.mp4").is_file()
        item["training_ready"] = phrase["verified"] is True and phrase["recognition_status"] == "in_model"
        phrases.append(item)
    verified = sum(1 for entry in phrases if entry["verified"] is True)
    body = json.dumps(phrases, ensure_ascii=False, indent=2)
    lines = [
        "// Generated by ai-engine/collection/export_phrase_vocabulary_for_frontend.py from dataset/metadata/phrase_vocabulary.json.",
        "// Do not edit by hand.",
        "",
        f"export const PHRASE_ENTRIES = {body};",
        "",
        f"export const PHRASE_VERIFIED_COUNT = {verified};",
        "",
    ]
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT}: {len(phrases)} phrases, {verified} verified")


if __name__ == "__main__":
    main()
