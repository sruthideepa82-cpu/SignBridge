"""Writes the official MediaPipe face connection sets to the frontend, so the overlay uses the same definitions.

Usage (from the backend folder):  python scripts/export_face_connections.py
"""

from pathlib import Path

from mediapipe.tasks.python.vision.face_landmarker import FaceLandmarksConnections

OUTPUT = Path(__file__).resolve().parents[2] / "frontend" / "src" / "lib" / "faceConnections.js"

SETS = {
    "FACE_OVAL": "FACE_LANDMARKS_FACE_OVAL",
    "LEFT_EYE": "FACE_LANDMARKS_LEFT_EYE",
    "RIGHT_EYE": "FACE_LANDMARKS_RIGHT_EYE",
    "LEFT_EYEBROW": "FACE_LANDMARKS_LEFT_EYEBROW",
    "RIGHT_EYEBROW": "FACE_LANDMARKS_RIGHT_EYEBROW",
    "NOSE": "FACE_LANDMARKS_NOSE",
    "LIPS": "FACE_LANDMARKS_LIPS",
}


def pairs_of(name: str) -> list[tuple[int, int]]:
    connections = getattr(FaceLandmarksConnections, name)
    return sorted((int(c.start), int(c.end)) for c in connections)


def main() -> None:
    lines = [
        "// Generated by backend/scripts/export_face_connections.py from MediaPipe's FaceLandmarksConnections.",
        "// Do not edit by hand. Index pairs refer to the 478 face landmarks in MediaPipe's order.",
        "",
    ]
    for key, source in SETS.items():
        pairs = pairs_of(source)
        body = ", ".join(f"[{a}, {b}]" for a, b in pairs)
        lines.append(f"// {source}: {len(pairs)} connections")
        lines.append(f"export const {key} = [{body}];")
        lines.append("")
    OUTPUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"Wrote {OUTPUT} ({', '.join(f'{k}={len(pairs_of(v))}' for k, v in SETS.items())})")


if __name__ == "__main__":
    main()
